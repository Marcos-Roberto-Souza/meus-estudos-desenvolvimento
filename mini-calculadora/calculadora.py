primeiroNumero =  10
segundoNumero = 5

soma = primeiroNumero + segundoNumero
subtracao = primeiroNumero - segundoNumero
multiplicacao = primeiroNumero * segundoNumero
divisao = primeiroNumero / segundoNumero
exponenciacao = primeiroNumero ** segundoNumero
restoDivisao = primeiroNumero % segundoNumero

print(f'{primeiroNumero} + {segundoNumero} = {soma}')
print(f'{primeiroNumero} - {segundoNumero} = {subtracao}')
print(f'{primeiroNumero} / {segundoNumero} = {divisao}')
print(f'{primeiroNumero} * {segundoNumero} = {multiplicacao}')
print(f'{primeiroNumero} ** {segundoNumero} = {exponenciacao}')
print(f'{primeiroNumero} % {segundoNumero} = {restoDivisao}')